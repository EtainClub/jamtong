import { z } from "zod";

/**
 * 잼공 4단계 「답하기」 — 쟁점에 답하기(기술 C1·C4). docs/jamgong-roadmap.md §3·R3.
 *
 * 업적의 반론(counterpoints) 하나가 문항 하나다. 반론의 질문은 지인이 보낸 메시지로, 위키가 쓴 답변(response)은 모범 답변으로 쓴다.
 * 배우는 사람은 ① 답의 뼈대를 고르고 ② 가장 곧바른 근거를 고른 뒤 ③ 모범 답변을 읽는다.
 *
 * ★ 뼈대(skeleton)는 모범 답변이 실제로 취한 모양이다 — 인정(admit), 바로잡기(correct), 모르는 건 모른다(unknown).
 *   "화제 돌리기"는 언제나 오답으로 보기에 들어간다(하지 말아야 할 답을 익힌다).
 * ★ evidence는 그 반론의 claimIds 가운데 하나, decoys는 같은 업적의 claim 가운데 반론의 claimIds가 아닌 것이다.
 *   decoys도 사실이다 — 질문에 답하지 않을 뿐이다. 반론·비판을 "물리칠 대상"으로 그리지 않는다.
 * ★ label은 claim을 줄인 것이다. 새 사실을 넣지 않는다.
 * ★ 초안은 GPT(Codex)가 반론·claim만 보고 썼고, 문항마다 원본과 대조해 고쳤다(docs/jamgong-r3-review.md).
 */
export const Skeleton = z.enum(["admit", "correct", "unknown"]);
export type Skeleton = z.infer<typeof Skeleton>;

const pick = z.object({ claimId: z.string(), label: z.string().min(8).max(60) });

export const debateItemSchema = z.object({
  id: z.string().regex(/^d[0-9]+$/),
  unit: z.string().regex(/^a:[a-z0-9-]+$/),
  counterpointId: z.string(),
  /** 지인이 보낸 메시지(반론 질문을 말투만 바꾼 것). */
  message: z.string().min(8).max(70),
  skeleton: Skeleton,
  /** 왜 그 뼈대인가 — 모범 답변의 첫머리를 근거로. */
  why: z.string().min(10),
  evidence: pick,
  decoys: z.array(pick).length(2),
});
export type DebateItem = z.infer<typeof debateItemSchema>;

